#!/usr/bin/env bash
# Verifies crm/migrations/*_krh_website_inquiries.sql against a THROWAWAY
# local Postgres cluster. Never touches the production CRM.
# Requires Homebrew postgresql@17 (or set PGBIN). Usage: crm/verify-migration-local.sh
set -euo pipefail
export LC_ALL=en_US.UTF-8
B="${PGBIN:-/opt/homebrew/opt/postgresql@17/bin}"
HERE="$(cd "$(dirname "$0")" && pwd)"
MIG="$(ls "$HERE"/migrations/*_krh_website_inquiries.sql | tail -1)"
D="$(mktemp -d "${TMPDIR:-/tmp}/krhpg.XXXX")"
PORT="${PGPORT_TEST:-55433}"
cleanup() { "$B/pg_ctl" -D "$D/data" stop -m fast >/dev/null 2>&1 || true; rm -rf "$D"; }
trap cleanup EXIT
"$B/initdb" -D "$D/data" -U postgres --auth=trust >/dev/null
"$B/pg_ctl" -D "$D/data" -o "-p $PORT -k $D -c listen_addresses=''" -l "$D/log" -w start >/dev/null
P=("$B/psql" -h "$D" -p "$PORT" -U postgres -v ON_ERROR_STOP=1 -q -X)
pass=0; fail=0
ok() { echo "PASS $1"; pass=$((pass+1)); }
bad() { echo "FAIL $1"; fail=$((fail+1)); }

# Minimal stand-ins for the Supabase roles and the CRM contacts table.
"${P[@]}" -c "create role anon nologin; create role authenticated nologin;
  create role authenticator login noinherit; grant anon, authenticated to authenticator;
  create table public.contacts(id bigint generated by default as identity primary key, email text);
  insert into public.contacts(email) values ('c@example.com');"

"${P[@]}" -f "$MIG" && ok "migration applies" || bad "migration applies"
"${P[@]}" -f "$MIG" 2>/dev/null && ok "migration is re-runnable" || bad "migration is re-runnable"

row() { # $1 inquiry_id  $2 key-char  [$3 extra col] [$4 extra val]
  local cols="inquiry_id,idempotency_key,received_at,contact_name,email,message_sha256${3:+,$3}"
  local vals="'$1',repeat('$2',64),now(),'T','t@example.com',repeat('b',64)${4:+,$4}"
  echo "insert into public.website_inquiries($cols) values ($vals)"
}
as_writer() { "${P[@]}" -c "set role krh_inquiry_writer; $1" >/dev/null 2>"$D/err"; }

as_writer "$(row KRH-INQ-20261117-ABCDEFGHIJ a)" && ok "writer can insert" || { bad "writer can insert"; cat "$D/err"; }
as_writer "$(row KRH-INQ-20261117-ABCDEFGHIJ a)" && bad "duplicate insert was accepted" || {
  grep -q "duplicate key value violates unique constraint" "$D/err" && ok "duplicate rejected by unique constraint (23505)" || { bad "duplicate error type"; cat "$D/err"; }; }
n=$("${P[@]}" -At -c "select count(*) from public.website_inquiries")
[ "$n" = "1" ] && ok "exactly one row after duplicate" || bad "row count after duplicate = $n"

deny() { as_writer "$2" && bad "$1 (was allowed)" || ok "$1 denied"; }
deny "writer SELECT *"          "select * from public.website_inquiries"
deny "writer SELECT count"      "select count(*) from public.website_inquiries"
deny "writer SELECT key column" "select idempotency_key from public.website_inquiries"
deny "writer UPDATE"            "update public.website_inquiries set email='x@example.com'"
deny "writer DELETE"            "delete from public.website_inquiries"
deny "writer read contacts"     "select * from public.contacts"
deny "writer set contact_id"    "$(row KRH-INQ-20261117-ABCDEFGHIK c contact_id 1)"
deny "bad inquiry_id format"    "$(row bad d)"
deny "anon insert"              "reset role; set role anon; $(row KRH-INQ-20261117-ABCDEFGHIL e)"

"${P[@]}" -c "set role authenticated; update public.website_inquiries set contact_id=1, reconciled_at=now();" >/dev/null 2>&1 \
  && ok "CRM user can reconcile" || bad "CRM user can reconcile"
"${P[@]}" -c "set role authenticated; update public.website_inquiries set email='x@example.com';" >/dev/null 2>&1 \
  && bad "CRM user edit intake email (was allowed)" || ok "CRM user cannot rewrite intake fields"

echo "migration checks: $pass passed, $fail failed"
[ "$fail" = 0 ]
